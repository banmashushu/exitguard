#!/bin/sh
# Prepare an ad-hoc signed native Mac release for review. Never install or run it.
set -eu
repo_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$repo_dir"
release_dir=${EXITGUARD_MAC_RELEASE_DIR:-"$repo_dir/.work/macos-native-release"}
case "$release_dir" in
  "$repo_dir/.work/"*) ;;
  *) printf '%s\n' 'Mac review releases must stay inside this project .work directory.' >&2; exit 1 ;;
esac
if [ -L "$release_dir" ] || { [ -e "$release_dir" ] && [ ! -f "$release_dir/.exitguard-native-release" ]; }; then
  printf '%s\n' 'Refusing to replace a directory that is not a generated native review release.' >&2
  exit 1
fi
release_parent=$(dirname -- "$release_dir")
mkdir -p "$release_parent"
staging_dir=$(mktemp -d "$release_parent/.macos-native-package.XXXXXX")
trap 'rm -rf "$staging_dir"' EXIT HUP INT TERM

sh scripts/build-desktop.sh darwin/arm64 "$staging_dir/mygo"
app_dir="$staging_dir/ExitGuard.app"
ditto "$staging_dir/mygo/darwin-arm64/ExitGuard.app" "$app_dir"
cp platform/macos/README-native.txt "$app_dir/Contents/Resources/README-zh-CN.txt"
cp platform/windows/desktop/THIRD-PARTY-NOTICES.txt "$app_dir/Contents/Resources/THIRD-PARTY-NOTICES.txt"
python3 - "$app_dir/Contents/Resources/THIRD-PARTY-NOTICES.txt" <<'PYNOTICE'
from pathlib import Path
import sys
path = Path(sys.argv[1])
text = path.read_text()
text = text.replace("ExitGuard Windows native desktop", "ExitGuard native desktop", 1)
text = text.replace("NSIS 3.13 is used unmodified for the installer.", "NSIS applies only to the Windows installer; it is not part of this Mac app.\nNSIS 3.13 is used unmodified for the Windows installer.", 1)
path.write_text(text)
PYNOTICE
# Resource additions must be sealed after the bundle is complete.
codesign --force --sign - "$app_dir"
archive="$staging_dir/ExitGuard-macOS-arm64-latest.zip"
ditto -c -k --keepParent --norsrc --noextattr --noacl "$app_dir" "$archive"
python3 scripts/verify-macos-desktop.py "$app_dir" "$archive"
(
  cd "$staging_dir"
  shasum -a 256 ExitGuard-macOS-arm64-latest.zip > ExitGuard-macOS-arm64-SHA256SUMS.txt
)
rm -rf "$staging_dir/mygo"
printf '%s\n' 'Generated by scripts/package-macos-desktop.sh; review output only.' > "$staging_dir/.exitguard-native-release"
if [ -e "$release_dir" ]; then
  previous="$staging_dir.previous"
  mv "$release_dir" "$previous"
  if ! mv "$staging_dir" "$release_dir"; then
    mv "$previous" "$release_dir"
    exit 1
  fi
  rm -rf "$previous"
else
  mv "$staging_dir" "$release_dir"
fi
printf '%s\n' "Prepared: $release_dir/ExitGuard.app" \
  "Prepared: $release_dir/ExitGuard-macOS-arm64-latest.zip" \
  'Review stage only. No app was installed or launched; existing dist archives remain untouched.'
