#!/bin/sh
# Build release assets from one clean main commit. Never upload, install or run.
set -eu
repo_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$repo_dir"
release_commit=${EXITGUARD_RELEASE_COMMIT:?Set EXITGUARD_RELEASE_COMMIT to the full main commit SHA}
test "$(git rev-parse HEAD)" = "$release_commit"
test "$(git rev-parse refs/heads/main)" = "$release_commit"
git diff --quiet HEAD --
test -z "$(git ls-files --others --exclude-standard -- . ':!.idea')"
version=$(python3 -c 'import json; print(json.load(open("mygo.json"))["version"])')
release_dir="$repo_dir/.work/release-v$version"
if [ -L "$release_dir" ] || { [ -e "$release_dir" ] && [ ! -f "$release_dir/.exitguard-github-release" ]; }; then
  printf '%s\n' 'Refusing to replace an unrelated release directory.' >&2
  exit 1
fi
mkdir -p "$repo_dir/.work"
stage=$(mktemp -d "$repo_dir/.work/.release-v$version.XXXXXX")
# Keep a failed stage for diagnosis rather than remove a potentially mounted image.
printf '%s\n' "Release staging: $stage"
mkdir "$stage/logs"
EXITGUARD_MAC_RELEASE_DIR="$stage/mac-build" \
  sh scripts/package-macos-desktop.sh > "$stage/logs/macos-build.log" 2>&1
EXITGUARD_OUTPUT_DIR="$stage/win-build" EXITGUARD_WINDOWS_VALIDATION_DIR="$stage/logs/windows" \
  sh scripts/package-windows-desktop.sh > "$stage/logs/windows-build.log" 2>&1
cp "$stage/mac-build/ExitGuard-macOS-arm64-latest.zip" "$stage/ExitGuard-macOS-arm64.zip"
cp "$stage/win-build/ExitGuard-Windows-x64-Setup.exe" "$stage/ExitGuard-Windows-x64-Setup.exe"
cp "$stage/win-build/ExitGuard-Windows-x64.zip" "$stage/ExitGuard-Windows-x64.zip"
mkdir "$stage/dmg-source"
ditto "$stage/mac-build/ExitGuard.app" "$stage/dmg-source/ExitGuard.app"
ln -s /Applications "$stage/dmg-source/Applications"
hdiutil create -fs HFS+ -format UDZO -volname ExitGuard \
  -srcfolder "$stage/dmg-source" "$stage/ExitGuard-macOS-arm64.dmg" > "$stage/logs/dmg-create.log" 2>&1
hdiutil verify "$stage/ExitGuard-macOS-arm64.dmg" > "$stage/logs/dmg-verify.log" 2>&1
python3 - "$stage" "$repo_dir" <<'PYRELEASE'
from pathlib import Path
import hashlib
import json
import os
import subprocess
import sys
import zipfile

stage, repo = map(Path, sys.argv[1:])
mount = stage / "dmg-mount"
mount.mkdir()
attach = subprocess.check_output(["hdiutil", "attach", "-readonly", "-nobrowse", "-noautoopen", "-mountpoint", str(mount), "-plist", str(stage / "ExitGuard-macOS-arm64.dmg")])
(stage / "logs/dmg-attach.plist").write_bytes(attach)
try:
    assert {p.name for p in mount.iterdir()} == {"ExitGuard.app", "Applications"}, "unexpected DMG root entries"
    assert (mount / "Applications").is_symlink() and os.readlink(mount / "Applications") == "/Applications", "wrong Applications link"
    assert (mount / "ExitGuard.app").is_dir() and not (mount / "ExitGuard.app").is_symlink()
    with (stage / "logs/dmg-mounted-verify.log").open("wb") as log:
        subprocess.run([sys.executable, str(repo / "scripts/verify-macos-desktop.py"), str(mount / "ExitGuard.app"), str(stage / "ExitGuard-macOS-arm64.zip")], stdout=log, stderr=subprocess.STDOUT, check=True)
finally:
    subprocess.run(["hdiutil", "detach", str(mount)], check=True)
mount.rmdir()
license_text = (repo / "LICENSE").read_bytes()
assert b"Copyright (c) 2026 banmashushu" in license_text
for archive, notice in (("ExitGuard-macOS-arm64.zip", "ExitGuard.app/Contents/Resources/THIRD-PARTY-NOTICES.txt"), ("ExitGuard-Windows-x64.zip", "THIRD-PARTY-NOTICES.txt")):
    with zipfile.ZipFile(stage / archive) as package:
        assert license_text in package.read(notice), "original MIT license missing from binary release"
names = ("ExitGuard-macOS-arm64.dmg", "ExitGuard-macOS-arm64.zip", "ExitGuard-Windows-x64-Setup.exe", "ExitGuard-Windows-x64.zip")
assets = {name: {"bytes": (stage / name).stat().st_size, "sha256": hashlib.sha256((stage / name).read_bytes()).hexdigest()} for name in names}
(stage / "SHA256SUMS.txt").write_bytes("".join(f"{item['sha256']}  {name}\n" for name, item in assets.items()).encode("ascii"))
(stage / "logs/assets.json").write_text(json.dumps(assets, indent=2) + "\n")
print(json.dumps(assets, indent=2))
PYRELEASE
git diff --quiet HEAD --
test "$(git rev-parse HEAD)" = "$release_commit"
test -z "$(git ls-files --others --exclude-standard -- . ':!.idea')"
printf '%s\n' "$release_commit" > "$stage/logs/source-commit.txt"
rm -rf "$stage/mac-build" "$stage/win-build" "$stage/dmg-source"
printf '%s\n' 'Generated by scripts/package-release.sh.' > "$stage/.exitguard-github-release"
if [ -e "$release_dir" ]; then
  previous="$stage.previous"
  mv "$release_dir" "$previous"
  if ! mv "$stage" "$release_dir"; then
    mv "$previous" "$release_dir"
    exit 1
  fi
  rm -rf "$previous"
else
  mv "$stage" "$release_dir"
fi
printf '%s\n' "Prepared Release assets: $release_dir" 'No files were uploaded or installed.'
